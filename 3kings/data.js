const THREE_KINGDOMS_DATA = {
  nodes: [],
  links: []
};

// 寫入人物節點
CHARACTERS.forEach(char => {
  THREE_KINGDOMS_DATA.nodes.push({
    id: char.id,
    type: "character",
    group: char.group,
    description: char.desc,
    games: char.games
  });
});

// 寫入事件節點
Object.keys(EVENTS_DETAILS).forEach(eventName => {
  THREE_KINGDOMS_DATA.nodes.push({
    id: eventName,
    type: "event",
    group: "事件",
    description: EVENTS_DETAILS[eventName].desc,
    year: EVENTS_DETAILS[eventName].year,
    games: EVENTS_DETAILS[eventName].games
  });
});

// 篩選出 DIRECT_LINKS 中 source 和 target 都存在於 nodes 中的連線
const validNodeIds = new Set(THREE_KINGDOMS_DATA.nodes.map(n => n.id));
const filteredLinks = DIRECT_LINKS.filter(l => {
  const srcId = typeof l.source === 'string' ? l.source : l.source.id;
  const tgtId = typeof l.target === 'string' ? l.target : l.target.id;
  return validNodeIds.has(srcId) && validNodeIds.has(tgtId);
});

THREE_KINGDOMS_DATA.links = filteredLinks;

